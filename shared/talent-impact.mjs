export function talentImpact(statistics, build, selected) {
  const pairs = statistics.filter(row => row.build === build && selected.includes(row.talent))
  const informative = pairs.filter(row => row.logWeight !== 0)
  const logWeight = informative.reduce((sum, row) => sum + row.logWeight, 0) / (informative.length || 1)
  return { pairs, logWeight }
}

export function applyTalentImpact(probabilities, impacts) {
  if (!impacts.some(impact => impact.logWeight !== 0)) return probabilities
  const adjusted = probabilities.map((value, index) => value * Math.exp(impacts[index].logWeight))
  const total = adjusted.reduce((sum, value) => sum + value, 0)
  return adjusted.map(value => value / total)
}
